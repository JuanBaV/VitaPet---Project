        public static string Obtener(string clave)
        {
            return VitaPet.GUI.Resources.Textos.ResourceManager.GetString(clave, CultureInfo.CurrentUICulture) ?? clave;
        }

        public static string Formato(string clave, params object[] valores)
        {
            return string.Format(CultureInfo.CurrentCulture, Obtener(clave), valores);
        }

        public static string Error(string codigo, string alternativa)
        {
            return VitaPet.GUI.Resources.Textos.ResourceManager.GetString("Error_" + codigo, CultureInfo.CurrentUICulture)
                ?? Traducir(alternativa);
        }

        public static string Traducir(string texto)
        {
            if (string.IsNullOrEmpty(texto)) return texto;
            string clave;
            if (Claves.TryGetValue(texto, out clave)) return Obtener(clave);
            var perfil = Regex.Match(texto, @"^(Guardado de perfil|Eliminación de perfil): (.+)$");
            if (perfil.Success) return Formato(perfil.Groups[1].Value == "Guardado de perfil" ? "Perfil_EventoGuardado" : "Perfil_EventoEliminado", perfil.Groups[2].Value);
            // Descripciones de backup: fecha e identificador permanecen intactos.
            if (texto.EndsWith(" | Verificado", StringComparison.Ordinal))
                return texto.Substring(0, texto.Length - "Verificado".Length) + Obtener("UI_Verificado");
            var evento = Regex.Match(texto, @"^(Backup realizado|Restauración realizada|Restore realizado) (.+)$");
            if (evento.Success) return Formato(evento.Groups[1].Value == "Backup realizado" ? "EventoBackup" : "EventoRestore", evento.Groups[2].Value);
            var usuario = Regex.Match(texto, @"^(Consulta de usuario|Modificación de usuario|Bloqueo de usuario|Desbloqueo de usuario) \(idUsuario=(\d+)\)$");
            if (usuario.Success) return Formato("OperacionUsuarioAuditoria", Traducir(usuario.Groups[1].Value), usuario.Groups[2].Value);
            var diagnostico = Regex.Match(texto, @"^ER023 \[([a-f0-9]{8})\] Tabla=(.+?); Fila=(.+?); Campo=(.+?); (.+)$");
            if (diagnostico.Success) return Formato("Bitacora_Diagnostico", diagnostico.Groups[1].Value,
                diagnostico.Groups[2].Value, diagnostico.Groups[3].Value, diagnostico.Groups[4].Value,
                Traducir(diagnostico.Groups[5].Value));
            var error = Regex.Match(texto, @"^(ER\d{3})[: -]+(.+)$");
            if (error.Success) return error.Groups[1].Value + " - " + Error(error.Groups[1].Value, error.Groups[2].Value);
            return texto;
        }
